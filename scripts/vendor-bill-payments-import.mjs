const args = process.argv.slice(2);
const arg = (name) => args.find((a) => a.startsWith(`--${name}=`))?.split("=")[1];
const APPLY = args.includes("--apply");
const ALLOW_OVERPAYMENT = args.includes("--allow-overpayment");
const DUMP_JSON = args.includes("--dump-json");
const VENDOR_FILTER = arg("vendor");

const IMPORT_IDENTITY = { name: "Bulk Import", email: "import@system", branch: "" };
const inr = (n) => "Rs " + Number(n).toLocaleString("en-IN", { maximumFractionDigits: 2 });
const r2 = (n) => Math.round((Number(n) || 0) * 100) / 100;
const escapeRegex = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

if (DUMP_JSON) {
  const out = "vendor-payments-payload.json";
  fs.writeFileSync(out, JSON.stringify(PAYMENT_ENTRIES, null, 2));
  console.log(`Wrote ${out} — ${PAYMENT_ENTRIES.length} row(s).`);
  process.exit(0);
}

if (!MONGODB_URI) {
  console.error("MONGODB_URI missing — checked .env.local and .env.");
  process.exit(1);
}

const ALL_ENTRIES = VENDOR_FILTER ? PAYMENT_ENTRIES.filter((e) => e.vendorName === VENDOR_FILTER) : PAYMENT_ENTRIES;
const paymentRows = ALL_ENTRIES.filter((e) => e.rowKind === "PAYMENT");
const unpaidInfoRows = ALL_ENTRIES.filter((e) => e.rowKind === "UNPAID_INFO");
const advanceRows = ALL_ENTRIES.filter((e) => e.rowKind === "ADVANCE_UNADJUSTED");

const VALID_METHODS = ["cash", "hdfc_skin_bank_transfer", "hdfc_ryan_medihub_bank_transfer", "icici_medihub_bank_transfer"];

function validate() {
  const errors = [];
  for (const e of paymentRows) {
    const where = `row ${e.rowNum} (${e.vendorName})`;
    if (!VALID_METHODS.includes(e.method)) errors.push(`${where}: unmapped method "${e.method}"`);
    if (!e.furtherMode) errors.push(`${where}: missing furtherMode`);
    if (!(e.amountAllocated > 0)) errors.push(`${where}: amount must be > 0`);
    if (isNaN(new Date(e.date).getTime())) errors.push(`${where}: bad date "${e.date}"`);
  }
  return errors;
}

async function run() {
  console.log("=".repeat(90));
  console.log(APPLY ? "MODE: APPLY  <- will write to the database" : "MODE: DRY RUN  <- nothing will be written");
  console.log(`Payment rows: ${paymentRows.length}  |  Unpaid-info rows (skipped): ${unpaidInfoRows.length}  |  Advance/ON ACCOUNT rows (skipped): ${advanceRows.length}`);
  if (VENDOR_FILTER) console.log(`Vendor filter: ${VENDOR_FILTER}`);
  console.log("=".repeat(90) + "\n");

  const errors = validate();
  if (errors.length) {
    console.error(`VALIDATION FAILED — ${errors.length} problem(s). Nothing imported.\n`);
    errors.forEach((e) => console.error("  " + e));
    process.exit(1);
  }
  console.log("Validation passed.\n");

  const sheetTotal = r2(paymentRows.reduce((s, e) => s + e.amountAllocated, 0));
  console.log(`Sum of Amount Allocated across real payment rows: ${inr(sheetTotal)}`);
  if (advanceRows.length) {
    console.log(`\n${advanceRows.length} advance/ON ACCOUNT row(s) totalling ${inr(r2(advanceRows.reduce((s, e) => s + e.amountAllocated, 0)))} will NOT be imported — see header note (no vendor-advance concept in this schema yet):`);
    advanceRows.forEach((e) => console.log(`  row ${e.rowNum}  ${e.vendorName}  ${e.date}  ${inr(e.amountAllocated)}  (Vch ${e.vchNo})`));
  }
  console.log("");

  await mongoose.connect(MONGODB_URI, { serverSelectionTimeoutMS: 8000 });
  const Vendor = mongoose.models.Vendor || mongoose.model("Vendor", new mongoose.Schema({}, { strict: false, collection: "vendors" }));
  const Payable = mongoose.models.Payable || mongoose.model("Payable", new mongoose.Schema({}, { strict: false, collection: "payables" }));
  const Transactions = mongoose.models.Transactions || mongoose.model("Transactions", new mongoose.Schema({}, { strict: false, collection: "transactions" }));

  const BULK_TAG_RE = /\[BULK-VENDOR-BILL-(\d+)\]/;
  const UNSETTLED_METHODS = ["paid_to_external", "paid_by_other"];

  console.log("Resolving vendors, loading bill order, and replaying the payment sequence...\n");

  const vendorGroups = new Map();
  for (const e of paymentRows) {
    if (!vendorGroups.has(e.vendorName)) vendorGroups.set(e.vendorName, []);
    vendorGroups.get(e.vendorName).push(e);
  }

  const resolved = [];
  for (const [vendorName, rows] of vendorGroups) {
    const vendor = await Vendor.findOne({ name: vendorName }).select("_id name").lean();
    if (!vendor) {
      rows.forEach((e) => resolved.push({ e, status: "vendor-not-found" }));
      continue;
    }

    const rawPayables = await Payable.find({ "payee.refId": vendor._id, "payee.kind": "VENDOR" })
      .select("_id totalAmount remarks expenseCategory expenseSubType isCancelled")
      .lean();
    const tagged = rawPayables
      .map((p) => {
        const m = p.remarks?.match(BULK_TAG_RE);
        return m ? { ...p, billRowNum: parseInt(m[1], 10) } : null;
      })
      .filter(Boolean)
      .sort((a, b) => a.billRowNum - b.billRowNum);

    if (!tagged.length) {
      rows.forEach((e) => resolved.push({ e, status: "no-bills-found", vendor }));
      continue;
    }

    let billIdx = 0;
    for (const e of rows) {
      const paymentId = `BULK-VENDOR-PAYMENT-${e.rowNum}`;
      const already = await Transactions.findOne({ paymentId }).select("_id").lean();
      if (already) {
        resolved.push({ e, status: "already-imported", existingId: String(already._id) });
        if (e.status === "Settled" && billIdx < tagged.length - 1) billIdx++;
        continue;
      }

      if (billIdx >= tagged.length) {
        resolved.push({ e, status: "ran-out-of-bills", vendor });
        continue;
      }

      const payable = tagged[billIdx];

      const [paidAgg] = await Transactions.aggregate([
        { $match: { payableId: payable._id, approvalStatus: "APPROVED", method: { $nin: UNSETTLED_METHODS } } },
        { $group: { _id: null, paid: { $sum: "$amount" } } },
      ]);
      const currentPaid = paidAgg?.paid || 0;
      const remaining = r2(payable.totalAmount - currentPaid);

      if (e.amountAllocated > remaining && !ALLOW_OVERPAYMENT) {
        resolved.push({ e, status: "overpay", vendor, payable, currentPaid, remaining });
        continue;
      }

      resolved.push({ e, status: "ok", vendor, payable, paymentId });

      if (e.status === "Settled" && billIdx < tagged.length - 1) billIdx++;
    }
  }

  const ok = resolved.filter((r) => r.status === "ok");
  const already = resolved.filter((r) => r.status === "already-imported");
  const notFound = resolved.filter((r) => r.status === "vendor-not-found");
  const noBills = resolved.filter((r) => r.status === "no-bills-found");
  const ranOut = resolved.filter((r) => r.status === "ran-out-of-bills");
  const overpay = resolved.filter((r) => r.status === "overpay");

  console.log(`  OK to import          : ${ok.length}`);
  console.log(`  Already imported       : ${already.length}  (idempotent — safe re-run, skipped)`);
  console.log(`  Vendor not found       : ${notFound.length}`);
  console.log(`  No tagged bills found  : ${noBills.length}  (run vendor-payables-bulk-import.mjs first)`);
  console.log(`  Ran out of bills       : ${ranOut.length}  (more payments than bills — needs review)`);
  console.log(`  Exceeds remaining      : ${overpay.length}  (pass --allow-overpayment to force)`);

  for (const [label, list] of [
    ["VENDOR NOT FOUND", notFound],
    ["NO TAGGED BILLS FOUND", noBills],
    ["RAN OUT OF BILLS", ranOut],
    ["EXCEEDS REMAINING", overpay],
  ]) {
    if (!list.length) continue;
    console.log(`\n--- ${label} (skipped) ---`);
    list.forEach((r) =>
      console.log(
        `  row ${r.e.rowNum}  ${r.e.vendorName.padEnd(38)} ${inr(r.e.amountAllocated).padStart(12)}  ${r.remaining !== undefined ? `(only ${inr(r.remaining)} remains)` : ""}`,
      ),
    );
  }

  if (!APPLY) {
    console.log("\nDRY RUN — nothing written. Re-run with --apply once the lists above look right.");
    await mongoose.disconnect();
    return;
  }

  console.log(`\nCreating ${ok.length} transaction(s)...`);
  const created = [];
  const failed = [];

  for (const { e, vendor, payable, paymentId } of ok) {
    try {
      const remarks = `[BULK-VENDOR-PAYMENT-${e.rowNum}] ${e.billType} payment, Vch ${e.vchNo}, status ${e.status} — against payable ${payable._id}`;
      const doc = await Transactions.create({
        transactionCategory: "EXPENSE",
        costType: "Expenses",
        expense: payable.expenseCategory,
        expenseType: payable.expenseSubType,
        payableId: payable._id,
        amount: e.amountAllocated,
        method: e.method,
        paymentId,
        date: new Date(e.date),
        remarks,
        receipts: [],
        furtherMode: e.furtherMode,
        receiptMode: "",
        isSettlement: payable.costAlreadyRecognised === true,
        vendor: vendor._id,
        approvalStatus: "APPROVED",
        createdBy: { ...IMPORT_IDENTITY, date: new Date() },
      });
      created.push({ rowNum: e.rowNum, vendorName: e.vendorName, id: String(doc._id), amount: e.amountAllocated });
      console.log(`  row ${String(e.rowNum).padStart(3)}  ${e.vendorName.padEnd(38)} ${inr(e.amountAllocated).padStart(12)}  OK`);
    } catch (err) {
      failed.push({ rowNum: e.rowNum, vendorName: e.vendorName, reason: err?.message || String(err) });
      console.log(`  row ${String(e.rowNum).padStart(3)}  ${e.vendorName.padEnd(38)}  FAILED: ${err?.message || err}`);
    }
  }

  console.log(`\nCreated ${created.length} transaction(s), ${failed.length} failed.`);
  if (failed.length) {
    console.log("\nFailed rows:");
    failed.forEach((f) => console.log(`  row ${f.rowNum}  ${f.vendorName}: ${f.reason}`));
  }

  const reportPath = `vendor-payments-import-report-${Date.now()}.json`;
  fs.writeFileSync(
    reportPath,
    JSON.stringify(
      {
        source: "aaaaaaaaaaaaa.xlsx",
        created,
        failed,
        skippedUnpaidInfo: unpaidInfoRows.map((e) => ({ rowNum: e.rowNum, vendorName: e.vendorName })),
        skippedAdvanceUnadjusted: advanceRows.map((e) => ({ rowNum: e.rowNum, vendorName: e.vendorName, amount: e.amountAllocated })),
        skippedVendorNotFound: notFound.map((r) => ({ rowNum: r.e.rowNum, vendorName: r.e.vendorName })),
        skippedNoBillsFound: noBills.map((r) => ({ rowNum: r.e.rowNum, vendorName: r.e.vendorName })),
        skippedRanOutOfBills: ranOut.map((r) => ({ rowNum: r.e.rowNum, vendorName: r.e.vendorName, amount: r.e.amountAllocated })),
        skippedOverpay: overpay.map((r) => ({ rowNum: r.e.rowNum, vendorName: r.e.vendorName, amount: r.e.amountAllocated })),
        alreadyImported: already.map((r) => ({ rowNum: r.e.rowNum, vendorName: r.e.vendorName, existingId: r.existingId })),
      },
      null,
      2,
    ),
  );
  console.log(`\nReport written to ${reportPath} — keep it, the IDs are your undo list.`);

  await mongoose.disconnect();
  console.log("Done.");
}

run().catch(async (err) => {
  console.error("\nFATAL:", err);
  await mongoose.disconnect().catch(() => {});
  process.exit(1);
});
